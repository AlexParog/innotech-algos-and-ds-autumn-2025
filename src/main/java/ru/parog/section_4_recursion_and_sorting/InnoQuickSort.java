package ru.parog.section_4_recursion_and_sorting;

public class InnoQuickSort {

    /**
     * Сортируем массив с помощью алгоритма быстрой сортировки.
     *
     * @param arr массив
     */
    public static void quickSort(int[] arr) {
        if (arr == null || arr.length < 1) {
            throw new IllegalArgumentException("Массив не может быть пустым");
        }
        quickSort(arr, 0, arr.length - 1);
    }

    /**
     * Рекурсивно сортирует подмассив. Элементы будут отсортированы в порядке возрастания.
     * <p>
     * Изначально проверяем базовый случай: если low >= high, подмассив содержит 0 или 1 элемент и уже отсортирован.
     * Далее вызываем метод partition(int[], int, int) для разделения массива относительно опорного элемента. Рекурсивно
     * сортирует левую часть (элементы меньше опорного). Рекурсивно сортирует правую часть (элементы больше опорного).
     *
     * @param arr  массив целых чисел для сортировки
     * @param low  начальный индекс подмассива (включительно)
     * @param high конечный индекс подмассива (включительно)
     */
    private static void quickSort(int[] arr, int low, int high) {
        if (low < high) {
            // опорный индекс
            int pivotIndex = partition(arr, low, high);
            // сортировка левой части до pivot
            quickSort(arr, low, pivotIndex - 1);
            // сортировка правой части после pivot
            quickSort(arr, pivotIndex + 1, high);
        }
    }

    /**
     * В качестве опорного элемента выбирается arr[high] (последний элемент). Указатель i отмечает границу "малых"
     * элементов. Проходимся по массиву [low, high -1]. Увеличиваем i, если arr[j] <= pivot, и меняем местами arr[i] и arr[j].
     * Таким образом получаем, что все элементы <= pivot перемещаются влево. После цикла ставит опорный элемент на
     * правильную позицию: swap(arr, i+1, high).
     *
     * @param arr  массив целых чисел
     * @param low  начальный индекс подмассива (включительно)
     * @param high конечный индекс подмассива (включительно), элемент используется как опорный
     * @return индекс, на котором находится опорный элемент после разделения
     */
    private static int partition(int[] arr, int low, int high) {
        int pivot = arr[high];
        int i = low - 1;

        for (int j = low; j < high; j++) {
            // Если текущий элемент меньше или равен опорному
            if (arr[j] <= pivot) {
                // Расширяем область "малых" элементов
                i++;
                // Перемещаем текущий элемент в область "малых"
                swap(arr, i, j);
            }
        }
        // Ставим опорный элемент на правильную позицию
        // между "малыми" и "большими" элементами
        swap(arr, i + 1, high);
        // индекс опорного элемента
        return i + 1;
    }

    /**
     * Меняет местами два элемента в массиве.
     *
     * @param arr массив, в котором происходит обмен
     * @param i   индекс первого элемента
     * @param j   индекс второго элемента
     */
    private static void swap(int[] arr, int i, int j) {
        int temp = arr[i];
        arr[i] = arr[j];
        arr[j] = temp;
    }
}
